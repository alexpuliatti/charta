import { cp, mkdir, readFile, writeFile } from 'node:fs/promises';
import { buildPDFStyles } from './pdf-styles.mjs';

// Keep rendering offline and pin the API, viewer, and worker to one version.
const source = new URL('../node_modules/pdfjs-dist/', import.meta.url);
const destination = new URL('../web/vendor/pdfjs/', import.meta.url);
await mkdir(destination, { recursive: true });
for (const [from, to] of [
  ['build/pdf.min.mjs', 'pdf.mjs'], ['build/pdf.worker.min.mjs', 'pdf.worker.mjs'],
  ['web/pdf_viewer.mjs', 'pdf_viewer.mjs'], ['web/pdf_viewer.css', 'pdf_viewer.css'],
  ['web/images', 'images'], ['cmaps', 'cmaps'], ['standard_fonts', 'standard_fonts'],
  ['wasm', 'wasm'], ['LICENSE', 'LICENSE'],
  ['iccs', 'iccs'],
]) await cp(new URL(from, source), new URL(to, destination), { recursive: true });
await buildPDFStyles();
const { version } = JSON.parse(await readFile(new URL('package.json', source), 'utf8'));
await writeFile(new URL('NOTICE.md', destination), `Mozilla PDF.js ${version}. Apache License 2.0; see LICENSE.\nVendored by scripts/vendor-pdf.mjs from the pinned pdfjs-dist package.\nThe original pdf_viewer.css is retained. pdf_viewer.scoped.css is generated by scripts/pdf-styles.mjs to confine all viewer styles and defaults to .custom-pdf-reader.\n`);
console.log(`Vendored PDF.js ${version}, viewer, worker, fonts, and image decoders.`);
