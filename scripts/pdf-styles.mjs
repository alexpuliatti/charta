import { transform } from 'esbuild';
import { readFile, writeFile } from 'node:fs/promises';

const directory = new URL('../web/vendor/pdfjs/', import.meta.url);

export async function buildPDFStyles({ check = false } = {}) {
  const source = await readFile(new URL('pdf_viewer.css', directory), 'utf8');
  // PDF.js also ships application-wide selectors such as .sidebar and :root.
  // Keep its defaults on the reader, without increasing selector specificity.
  const { code } = await transform(`:where(.custom-pdf-reader) {\n${source.replace(/:root\b/g, '&')}\n}`, {
    loader: 'css', supported: { nesting: false }, legalComments: 'inline',
  });
  const license = source.match(/^\/\*[\s\S]*?\*\//)?.[0] || '';
  const output = `${license}\n/* Generated by scripts/pdf-styles.mjs. Keep PDF.js styles inside the reader. */\n${code}`;
  const destination = new URL('pdf_viewer.scoped.css', directory);
  if (check) {
    if (await readFile(destination, 'utf8').catch(() => '') !== output) {
      throw new Error('Scoped PDF.js styles are out of date. Run npm run vendor:pdf.');
    }
  } else await writeFile(destination, output);
}
