  server = spawn(process.execPath, ['scripts/dev.mjs'], { cwd: temporary, env: { ...process.env, PORT: String(port) }, stdio: ['ignore', 'pipe', 'pipe'] });
  await new Promise((resolve, reject) => {
    const timeout = setTimeout(() => reject(new Error('Local server did not become ready.')), 15000);
    server.stdout.on('data', data => { if (String(data).includes('Charta is ready')) { clearTimeout(timeout); resolve(); } });
    server.stderr.on('data', data => { clearTimeout(timeout); reject(new Error(String(data))); });
    server.once('exit', code => { clearTimeout(timeout); reject(new Error(`Local server exited ${code}.`)); });
  });
  for (const file of ['/', '/app.mjs', '/micro.mjs', '/micro.css', '/glide-select.mjs', '/explore.mjs', '/explore.css', '/canvas.mjs', '/canvas.css', '/shared/canvas.mjs', '/shared/canvas-ai.mjs', '/network.mjs', '/store.mjs', '/github.mjs', '/operations.mjs', '/context-menu.mjs', '/menu-icons.mjs', '/menus.css', '/context-menu.css', '/motion.mjs', '/motion.css', '/assets/charta.svg', '/assets/charta-icon.svg', '/assets/icons/charta-32.png', '/shared/model.mjs', '/shared/taxonomy.mjs', '/shared/network.mjs', '/shared/semantic.mjs', '/shared/clip-markdown.mjs', '/article.mjs', '/article.css', '/dashboard.mjs', '/discover.mjs', '/discover.css', '/sidebar.mjs', '/folders.mjs', '/folders.css', '/resources.mjs', '/media-upload.mjs', '/video-upload-worker.mjs', '/vendor/mediabunny.mjs', '/browser-draft.mjs', '/resources.css', '/shared/uploads.mjs', '/shared/resource-routing.mjs', '/ambient.mjs', '/ambient.css', '/gradient-components.css', '/dark.css', '/workspace.css', '/minimal.css', '/reader-render.mjs', '/vendor/marked.umd.js', '/vendor/purify.min.js', '/styles.css', '/network.css', '/taxonomy.css', '/tokens.css', '/content/_generated/catalog.json', '/extension.zip']) {
    assert.equal((await fetch(base + file)).status, 200, `${file} should be served`);
  }
  const partial = await fetch(`${base}/content/blocks/b_source/body.md`, { headers: { Range: 'bytes=0-3' } });
  assert.equal(partial.status, 206, 'local media supports partial byte requests');
  assert.equal(await partial.text(), 'A so');
  assert.match(partial.headers.get('content-range'), /^bytes 0-3\//);
  assert.equal((await fetch(`${base}/content/blocks/b_source/body.md`, { headers: { Range: 'bytes=999999-' } })).status, 416);
  const mutate = async (op, origin = base) => {
    const response = await fetch(`${base}/api/mutate`, { method: 'POST', headers: { 'Content-Type': 'application/json', Origin: origin }, body: JSON.stringify(op) });
    const result = await response.json();
    return { status: response.status, ...result };
  };
  const before = await (await fetch(`${base}/api/library`)).json();
  const search = async (query, origin = base) => {
    const response = await fetch(`${base}/api/search/hybrid`, { method: 'POST', headers: { 'Content-Type': 'application/json', Origin: origin }, body: JSON.stringify({ query }) });
    return { status: response.status, ...await response.json() };
  };
  assert.equal((await search('source', 'https://untrusted.example')).status, 403);
  assert.equal((await search('')).status, 400);
  assert.equal((await search('x'.repeat(3001))).status, 400);
