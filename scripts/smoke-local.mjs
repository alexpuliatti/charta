  result = await mutate({ type: 'delete-collection', id: 'c_smoke' });
  assert.equal(result.status, 200, result.error);
  assert.ok(result.catalog.blocks.some(b => b.id === 'b_smoke'));
  result = await mutate({ type: 'delete-folder', id: 'f_smoke' });
  assert.equal(result.status, 200, result.error);
  result = await mutate({ type: 'delete-block', id: 'b_smoke' });
  assert.equal(result.status, 200, result.error);
  for (const name of ['block.json', 'body.md', 'summary.json']) await assert.rejects(readFile(path.join(temporary, `content/blocks/b_smoke/${name}`)), { code: 'ENOENT' });
  const reloaded = await (await fetch(`${base}/content/_generated/catalog.json`)).json();
  assert.equal(reloaded.blocks.some(b => b.id === 'b_smoke'), false);
  assert.ok(reloaded.collections.every(c => c.items.every(item => item.id !== 'b_smoke')));
  result = await mutate({ type: 'delete-collection', id: 'c_inbox' });
  assert.equal(result.status, 200, result.error);
  assert.equal(result.catalog.library.inboxCollectionId, undefined);
  assert.equal(result.catalog.collections.length, 0);
  assert.equal(result.catalog.blocks.length, before.blocks.length, 'removing Inbox keeps every original material');
  assert.equal(JSON.parse(await readFile(path.join(temporary, 'content/library.json'), 'utf8')).inboxCollectionId, undefined);
  result = await mutate({ type: 'add-block', block: { id: 'b_unfiled', type: 'text', title: 'Saved in All materials', category: 'Notes', tags: ['unfiled'] }, body: 'No collection is required.', collectionIds: [] });
  assert.equal(result.status, 200, result.error);
  const unfiled = await (await fetch(`${base}/api/library`)).json();
  assert.deepEqual(unfiled.blocks.find(b => b.id === 'b_unfiled').collectionIds, []);
  assert.equal(await readFile(path.join(temporary, 'content/blocks/b_unfiled/body.md'), 'utf8'), 'No collection is required.');
  const imageBytes = Buffer.from('iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+jRZkAAAAASUVORK5CYII=', 'base64');
