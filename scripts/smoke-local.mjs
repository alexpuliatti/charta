  assert.equal(result.catalog.blocks.filter(b => b.id === 'b_smoke').length, 1);
  assert.equal(result.catalog.blocks.find(b => b.id === 'b_smoke').collectionIds.length, 2);
  result = await mutate({ type: 'update-block', id: 'b_smoke', patch: { summary: 'An owner-written summary, kept separately.', category: 'Design', tags: ['#Interfaces', 'collecting'], related: ['b_source'] } });
  assert.equal(result.status, 200, result.error);
  const summary = JSON.parse(await readFile(path.join(temporary, 'content/blocks/b_smoke/summary.json'), 'utf8'));
  assert.equal(summary.editedByOwner, true);
  const oldCollectionPath = result.catalog.collections.find(c => c.id === 'c_smoke').path;
  result = await mutate({ type: 'update-collection', id: 'c_smoke', parentId: null });
  assert.equal(result.status, 200, result.error);
  const movedCollection = result.catalog.collections.find(c => c.id === 'c_smoke');
  assert.equal(movedCollection.parentId, null);
  assert.notEqual(movedCollection.path, oldCollectionPath);
  assert.deepEqual(movedCollection.items, [{ kind: 'block', id: 'b_smoke' }]);
  await assert.rejects(readFile(path.join(temporary, oldCollectionPath)), { code: 'ENOENT' });
  const rejected = await mutate({ type: 'create-folder', title: 'Unwanted cross-origin write' }, 'https://untrusted.example');
  assert.equal(rejected.status, 403);
  const invalid = await mutate({ type: 'add-block', block: { id: 'b_bad', type: 'link', title: 'Unsafe', source: { url: 'javascript:alert(1)' } }, collectionIds: [] });
