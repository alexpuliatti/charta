  assert.equal(published.blocks.find(b => b.id === 'b_smoke').summary.text, summary.text);
  assert.equal(published.blocks.find(b => b.id === 'b_smoke').category, 'Design');
  assert.deepEqual(published.blocks.find(b => b.id === 'b_smoke').tags, ['interfaces', 'collecting']);
  const network = buildNetwork(published, { relations: ['related', 'tag'] });
