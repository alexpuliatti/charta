  assert.equal(result.status, 200, result.error);
  assert.deepEqual(await readFile(path.join(temporary, 'content/blocks/b_imported_image/assets/original.png')), imageBytes);
  assert.equal((await fetch(`${base}/content/blocks/b_imported_image/assets/original.png`)).status, 200);
