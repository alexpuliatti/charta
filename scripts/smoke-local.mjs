  assert.equal((await fetch(`${base}/api/canvas/ai`, { method: 'POST', headers: { 'Content-Type': 'application/json', Origin: 'https://untrusted.example' }, body: '{}' })).status, 403);
  let canvasResult = await mutate({ type: 'create-canvas', id: 'canvas_smoke', title: 'Connected ideas' });
  assert.equal(canvasResult.status, 200, canvasResult.error);
  const canvas = canvasResult.catalog.library.canvases[0];
  canvas.nodes = [{ id: 'card_note', kind: 'note', title: 'A thought', text: 'Words that survive reloading.', color: 'lilac', x: -120, y: 30, width: 280, height: 250 }, { id: 'card_ref', kind: 'material', blockId: 'b_source', x: 300, y: 30, width: 280, height: 250 }];
  canvas.edges = [{ id: 'edge_thought', from: 'card_note', to: 'card_ref', label: 'Related idea' }];
  canvasResult = await mutate({ type: 'save-canvas', id: canvas.id, expectedRevision: 1, canvas });
  assert.equal(canvasResult.status, 200, canvasResult.error);
  const diskCanvas = JSON.parse(await readFile(path.join(temporary, 'content/library.json'), 'utf8')).canvases[0];
  assert.equal(diskCanvas.revision, 2);
  assert.deepEqual(diskCanvas.nodes, canvas.nodes);
  assert.deepEqual((await (await fetch(`${base}/api/library`)).json()).library.canvases[0], diskCanvas);
  assert.deepEqual((await (await fetch(`${base}/content/_generated/catalog.json`)).json()).library.canvases[0], diskCanvas);
  assert.equal((await mutate({ type: 'save-canvas', id: canvas.id, expectedRevision: 1, canvas })).status, 400, 'stale boards cannot replace newer edits');
  assert.equal((await mutate({ type: 'delete-canvas', id: canvas.id, expectedRevision: 2 })).status, 200);

  const title = 'An isolated smoke check';
  let result = await mutate({ type: 'add-block', block: { id: 'b_smoke', type: 'text', title, category: '  Knowledge  ', tags: ['#Collecting', 'collecting', 'Network'] }, body: 'A note whose bytes should survive a complete disk save and reload.', collectionIds: [before.library.inboxCollectionId] });
  assert.equal(result.status, 200, result.error);
  assert.equal(result.catalog.blocks.length, before.blocks.length + 1);
  const stored = JSON.parse(await readFile(path.join(temporary, 'content/blocks/b_smoke/block.json'), 'utf8'));
  assert.equal(stored.title, title);
  assert.equal((await search('smoke check')).results[0].id, 'b_smoke', 'saved changes invalidate the search snapshot');
  assert.equal(stored.category, 'Knowledge');
  assert.deepEqual(stored.tags, ['collecting', 'network']);
  assert.equal(stored.path, undefined, 'Derived catalog fields must not leak into canonical records');
  assert.match(await readFile(path.join(temporary, 'content/blocks/b_smoke/body.md'), 'utf8'), /survive/);
  result = await mutate({ type: 'create-folder', id: 'f_smoke', title: 'Smoke folder' });
  assert.equal(result.status, 200, result.error);
  result = await mutate({ type: 'create-collection', id: 'c_smoke', title: 'Smoke collection', parentId: 'f_smoke' });
  assert.equal(result.status, 200, result.error);
  assert.equal(result.catalog.collections.find(c => c.id === 'c_smoke').parentId, 'f_smoke');
