  assert.equal(found.mode, 'keywords', 'fixtures without embeddings clearly report keyword fallback');
  // Simulate two tabs opened from the same snapshot, through the actual HTTP API.
  const staleBase = operationBase(before, { type: 'update-block', id: 'b_source' });
  assert.equal((await mutate({ type: 'update-block', id: 'b_source', patch: { title: 'An edited isolated source' }, baseCatalog: staleBase })).status, 200);
  const conflict = await mutate({ type: 'update-block', id: 'b_source', patch: { title: 'An obsolete title' }, baseCatalog: staleBase });
  assert.equal(conflict.status, 400);
  assert.match(conflict.error, /changed outside Charta/);
  assert.equal((await mutate({ type: 'delete-block', id: 'b_source', baseCatalog: staleBase })).status, 400, 'a stale tab cannot delete an edited resource');
  const independent = await mutate({ type: 'update-block', id: 'b_source', patch: { description: 'An independent note' }, baseCatalog: staleBase });
  assert.equal(independent.status, 200);
  assert.equal(independent.catalog.blocks.find(block => block.id === 'b_source').title, 'An edited isolated source');
  assert.equal(JSON.parse(await readFile(path.join(temporary, 'content/blocks/b_source/block.json'), 'utf8')).title, 'An edited isolated source');
  assert.equal((await fetch(`${base}/api/search/ask`, { method: 'POST', headers: { 'Content-Type': 'application/json', Origin: 'https://untrusted.example' }, body: '{}' })).status, 403);
  // Boards persist through real writes, generated catalogs, and reloads.
