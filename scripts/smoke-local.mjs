  assert.match(savedArticle, /tags: \["long-form"\]/);
  assert.ok(savedArticle.endsWith(article.body + '\n'));
  result = await mutate({ type: 'update-folder', id: 'f_smoke', title: 'Renamed folder' });
  assert.equal(result.status, 200, result.error);
  assert.equal(JSON.parse(await readFile(path.join(temporary, 'content/collections/smoke-folder/folder.json'), 'utf8')).title, 'Renamed folder');
