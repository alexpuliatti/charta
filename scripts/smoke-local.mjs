  assert.equal(replay.alreadySaved, true);
  assert.equal(replay.catalog.blocks.length, result.catalog.blocks.length);
  assert.equal((await fetch(`${base}/api/resource/inspect`, { method: 'POST', headers: { 'Content-Type': 'application/json', Origin: 'https://untrusted.example' }, body: '{}' })).status, 403);
  console.log('Local integration passed: canvas layouts, revision conflicts, AI route protection, stale-tab conflicts, independent edits, assets, disk saves, folders, taxonomy, network connections, shared memberships, summaries, renames, removals, deletions, Inbox removal, unfiled saves, catalog rebuild, and rejected writes.');
