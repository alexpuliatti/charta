import test from 'node:test';
import assert from 'node:assert/strict';
import { mkdtemp, mkdir, writeFile, readFile, rm } from 'node:fs/promises';
import path from 'node:path';
import os from 'node:os';
import { applyCuration, checkCuration } from '../scripts/curate-archive.mjs';
import { loadLibrary } from '../scripts/library.mjs';
import { buildNetwork } from '../shared/network.mjs';
import { canonicalRecord } from '../shared/model.mjs';

test('curation preserves original collections and bodies, adds sections and explicitly suggested reading', async t => {
  const root = await mkdtemp(path.join(os.tmpdir(), 'jelly-curation-test-'));
  t.after(() => rm(root, { recursive: true, force: true }));
  const put = async (file, value) => { const target = path.join(root, file); await mkdir(path.dirname(target), { recursive: true }); await writeFile(target, typeof value === 'string' ? value : JSON.stringify(value)); };
  await put('content/library.json', { schemaVersion: 1, title: 'Jelly', inboxCollectionId: 'c_inbox' });
  await put('content/collections/inbox/collection.json', { schemaVersion: 1, id: 'c_inbox', title: 'Inbox', items: [] });
  await put('content/collections/original/folder.json', { schemaVersion: 1, id: 'f_old', title: 'Original' });
  await put('content/collections/original/reading/collection.json', { schemaVersion: 1, id: 'c_old', title: 'leggi', items: [{ kind: 'block', id: 'b_one' }, { kind: 'block', id: 'b_two' }] });
  for (const id of ['b_one', 'b_two']) {
    await put(`content/blocks/${id}/block.json`, { schemaVersion: 1, id, title: `Original ${id}`, type: 'text', assets: [], related: [], bodyPath: 'body.md', category: 'Old category', tags: ['old-tag'] });
    await put(`content/blocks/${id}/body.md`, `Original body for ${id}`);
  }
  const plan = { version: 'artifact-curation-v1', generatedAt: '2026-11-15T00:00:00Z', blocks: ['b_one', 'b_two'].map((id, i) => ({ id, originalTitle: `Original ${id}`, title: ['Design Culture', 'Design Practice'][i], section: 'Writing', subsection: 'Design', memberships: [{ section: 'Writing', subsection: 'Design' }], tags: ['design', 'writing'], reason: 'Reviewed saved article text.', confidence: 0.9 })), articleSuggestions: [{ sourceId: 'b_one', targetId: 'b_two', reason: 'Both discuss design practice.', authoredLink: false }] };
  const dry = await applyCuration(root, plan);
  assert.equal(dry.materials, 2);
  assert.equal((await loadLibrary(root)).blocks[0].title, 'Original b_one');
  await assert.rejects(applyCuration(root, { ...plan, blocks: [plan.blocks[0]] }, { apply: true }), /every material/);
  await assert.rejects(applyCuration(root, { ...plan, blocks: plan.blocks.map(entry => ({ ...entry, originalTitle: 'Stale' })) }, { apply: true }), /outdated/);
  await applyCuration(root, plan, { apply: true });
  const catalog = await loadLibrary(root);
  assert.equal(catalog.collections.find(collection => collection.id === 'c_old').parentId, 'f_old');
  assert.equal(catalog.folders.find(folder => folder.id === 'f_old').parentId, 'f_curated_archive');
  assert.equal(catalog.collections.find(collection => collection.id === 'c_curated_writing_design').items.length, 2);
  assert.equal(catalog.blocks[0].body, 'Original body for b_one');
  assert.deepEqual(catalog.blocks[0].related, []);
  assert.equal(catalog.blocks[0].suggestedRelated[0].method, 'curation-v1');
  assert.equal(catalog.blocks[0].curation.original.title, 'Original b_one');
  assert.equal(JSON.parse(await readFile(path.join(root, 'content/imports/curation/before.json'))).blocks.length, 2);
  assert.equal((await checkCuration(root)).state, 'ready');
  assert.ok(buildNetwork(catalog).edges.some(edge => edge.reasons.some(reason => reason.type === 'suggested')));
  await assert.rejects(applyCuration(root, plan, { apply: true }), /already been applied/);
  const historyPath = 'content/imports/curation/retired-collections.json';
  const history = { schemaVersion: 1, collections: catalog.collections.filter(collection => ['c_inbox', 'c_old'].includes(collection.id)).map(canonicalRecord) };
  await put(historyPath, history);
  await rm(path.join(root, 'content/collections/archive'), { recursive: true });
  await rm(path.join(root, 'content/collections/inbox'), { recursive: true });
  const library = { ...catalog.library };
  delete library.inboxCollectionId;
  await put('content/library.json', library);
  await assert.rejects(checkCuration(root), /Original collection changed/, 'missing live collections require explicitly registered history');
  library.curation.retiredCollectionsPath = historyPath;
  await put('content/library.json', library);
  const checked = await checkCuration(root);
  assert.equal(checked.state, 'ready');
  assert.equal(checked.retiredCollections, 2);
  assert.equal((await loadLibrary(root)).blocks.length, 2, 'removing collection metadata keeps canonical materials');
  await put('content/blocks/b_added/block.json', { schemaVersion: 1, id: 'b_added', type: 'text', title: 'A newly added resource', category: 'Writing', tags: ['notes'], assets: [], related: [], ingest: { operationId: 'b_added' } });
  assert.equal((await checkCuration(root)).addedMaterials, 1, 'new resources do not invalidate preservation of the original import');
  const tampered = structuredClone(history);
  tampered.collections.find(collection => collection.id === 'c_old').items.pop();
  await put(historyPath, tampered);
  await assert.rejects(checkCuration(root), /Original collection changed: c_old/, 'retired history still verifies the original membership lists');
  await put(historyPath, { ...history, collections: [...history.collections, history.collections[0]] });
  await assert.rejects(checkCuration(root), /Invalid retired collection history/, 'duplicate retired IDs cannot hide conflicting histories');
});
