import test from 'node:test';
import assert from 'node:assert/strict';
import { cp, mkdtemp, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import path from 'node:path';
import { pathToFileURL } from 'node:url';
import { JSDOM } from 'jsdom';
import { applyOperation } from '../shared/model.mjs';

async function setup(t) {
  const root = await mkdtemp(path.join(tmpdir(), 'charta-canvas-ui-'));
  await cp(new URL('../web/', import.meta.url), root, { recursive: true });
  await cp(new URL('../shared/', import.meta.url), path.join(root, 'shared'), { recursive: true });
  const { renderCanvas } = await import(pathToFileURL(path.join(root, 'canvas.mjs')));
  const dom = new JSDOM('<main></main>', { url: 'https://example.test/charta/', pretendToBeVisual: true });
  const globals = new Map();
  const install = (key, value) => { globals.set(key, Object.getOwnPropertyDescriptor(globalThis, key)); Object.defineProperty(globalThis, key, { configurable: true, writable: true, value }); };
  for (const key of ['document', 'AbortController', 'FormData']) install(key, dom.window[key]);
  let catalog = { schemaVersion: 1, library: { schemaVersion: 1, title: 'Canvas UI' }, folders: [], collections: [], blocks: [] };
  catalog = applyOperation(catalog, { type: 'add-block', block: { id: 'b_reference', title: 'A reference', type: 'text' }, body: 'A connected reference about learning.' }).catalog;
  catalog = applyOperation(catalog, { type: 'add-block', block: { id: 'b_private', title: 'Unrelated', type: 'text' }, body: 'Unrelated private words must not be sent.' }).catalog;
  catalog = applyOperation(catalog, { type: 'create-canvas', id: 'canvas_test', title: 'Research' }).catalog;
  const store = { catalog, fail: false, async apply(operation) { if (this.fail) { this.fail = false; throw new Error('Simulated disk failure'); } const result = applyOperation(this.catalog, operation); this.catalog = result.catalog; return result; } };
  const requests = [], messages = [];
  install('fetch', async (url, init = {}) => {
    if (init.method !== 'POST') return new Response(JSON.stringify({ configured: true, model: 'local-test' }), { headers: { 'Content-Type': 'application/json' } });
    requests.push(JSON.parse(init.body));
    return new Response(JSON.stringify({ title: '<img src=x onerror=alert(1)> Expanded', text: 'Try connecting ideas with examples and retrieval practice.' }));
  });
  let view = renderCanvas(dom.window.document.querySelector('main'), store, { boardId: 'canvas_test', onMessage: message => messages.push(message) });
  const doc = dom.window.document;
  const $ = selector => doc.querySelector(selector);
  const action = name => $(`[data-canvas-action=${name}]`).click();
  const input = (selector, value) => { const field = $(selector); field.focus(); field.value = value; field.dispatchEvent(new dom.window.Event('input', { bubbles: true })); return field; };
  const rect = () => { $('.canvas-stage').getBoundingClientRect = () => ({ x: 0, y: 0, left: 0, top: 0, width: 1000, height: 700, right: 1000, bottom: 700 }); };
  rect();
  const remount = () => { view.destroy(); view = renderCanvas(doc.querySelector('main'), store, { boardId: 'canvas_test', onMessage: message => messages.push(message) }); rect(); return view; };
  t.after(async () => { await view.flush(); view.destroy(); dom.window.close(); for (const [key, previous] of globals) { if (previous) Object.defineProperty(globalThis, key, previous); else delete globalThis[key]; } await rm(root, { recursive: true, force: true }); });
  await new Promise(resolve => setTimeout(resolve, 0));
  return { dom, doc, $, action, input, store, requests, messages, get view() { return view; }, remount };
}

test('canvas edits notes, links library materials, generates reviewed connected notes, and survives remount', async t => {
  const ctx = await setup(t), { $, action, input, store, dom, requests } = ctx;
  action('note');
  input('.canvas-note-title', '<script>A topic</script>');
  const text = input('.canvas-note-text', 'The main topic. Focus on this idea.');
  assert.equal($('.canvas-card h2').textContent, '<script>A topic</script>');
  assert.equal($('.canvas-card script'), null);
  $('[data-color=sage]').click();
  assert.ok($('.canvas-card').classList.contains('color-sage'));
  const original = structuredClone(store.catalog.blocks[0]);
  action('library'); $('[data-material=b_reference]').click();
  assert.equal(ctx.view.getBoard().nodes.length, 2);
  assert.deepEqual(store.catalog.blocks[0], original);
  const cards = [...ctx.doc.querySelectorAll('.canvas-card')];
  cards[0].querySelector('[data-connect]').click();
  ctx.doc.querySelectorAll('.canvas-card')[1].querySelector('[data-connect]').click();
  assert.equal(ctx.view.getBoard().edges.length, 1);
  action('close-panel');
  assert.equal($('.canvas-panel').hidden, true);
  $('.canvas-edge').dispatchEvent(new dom.window.KeyboardEvent('keydown', { key: 'Enter', bubbles: true }));
  assert.equal($('.canvas-panel').hidden, false, 'keyboard selection opens the floating inspector');
  input('.canvas-edge-label', 'Supports this thought');
  assert.equal($('.canvas-edge text').textContent, 'Supports this thought');
  $('.canvas-card').click();
  const selected = $('.canvas-note-text'); selected.selectionStart = 16; selected.selectionEnd = selected.value.length;
  selected.dispatchEvent(new dom.window.Event('select', { bubbles: true }));
  input('.canvas-ai-prompt', 'Expand with examples.');
  action('generate');
  await new Promise(resolve => setTimeout(resolve, 0));
  assert.equal(requests.length, 1);
  assert.equal(requests[0].text, 'Focus on this idea.');
  assert.equal(requests[0].context.length, 1);
  assert.doesNotMatch(JSON.stringify(requests), /Unrelated private/);
  assert.equal($('.canvas-ai-result img'), null, 'AI text is escaped');
  assert.match($('.canvas-ai-result h4').textContent, /Expanded/);
  assert.equal(ctx.view.getBoard().nodes.length, 2, 'AI previews do not change the board');
  action('keep-ai');
  assert.equal(ctx.view.getBoard().nodes.length, 3);
  assert.equal(ctx.view.getBoard().nodes[2].ai, true);
  assert.equal(ctx.view.getBoard().edges[1].label, 'Expanded with AI');
  assert.equal(ctx.view.getBoard().nodes[0].text, 'The main topic. Focus on this idea.', 'AI preserves the original note');
  await ctx.view.flush();
  const saved = structuredClone(store.catalog.library.canvases[0]);
  ctx.remount();
  assert.deepEqual(ctx.view.getBoard(), saved);
  assert.equal($('.canvas-save').textContent, 'All changes saved');
});

test('pointer movement and keyboard edits save geometry; undo and remove preserve the material library', async t => {
  const ctx = await setup(t), { $, action, dom, doc, store } = ctx;
  action('note');
  const before = ctx.view.getBoard().nodes[0];
  const pointer = (target, type, x, y) => { const event = new dom.window.MouseEvent(type, { bubbles: true, clientX: x, clientY: y, button: 0 }); Object.defineProperty(event, 'pointerId', { value: 1 }); target.dispatchEvent(event); };
  pointer($('.canvas-card h2'), 'pointerdown', 300, 200);
  pointer($('.canvas-stage'), 'pointermove', 400, 260);
  pointer($('.canvas-stage'), 'pointerup', 400, 260);
  let node = ctx.view.getBoard().nodes[0];
  assert.equal(node.x, before.x + 100); assert.equal(node.y, before.y + 60);
  const card = $('.canvas-card'); card.focus();
  card.dispatchEvent(new dom.window.KeyboardEvent('keydown', { key: 'ArrowRight', bubbles: true }));
  assert.equal(ctx.view.getBoard().nodes[0].x, before.x + 110);
  $('.canvas-resize').dispatchEvent(new dom.window.KeyboardEvent('keydown', { key: 'ArrowDown', shiftKey: true, bubbles: true }));
  assert.equal(ctx.view.getBoard().nodes[0].height, before.height + 20);
  action('undo'); assert.equal(ctx.view.getBoard().nodes[0].height, before.height);
  action('redo'); assert.equal(ctx.view.getBoard().nodes[0].height, before.height + 20);
  await ctx.view.flush();
  ctx.remount();
  assert.equal(ctx.view.getBoard().nodes[0].x, before.x + 110);
  action('library'); $('[data-material=b_reference]').click();
  doc.querySelectorAll('.canvas-card')[1].click(); action('remove');
  assert.equal(ctx.view.getBoard().nodes.length, 1);
  assert.equal(store.catalog.blocks.length, 2);
});

test('failed canvas saves retain edits and recovery, and retry clears the failure after a confirmed save', async t => {
  const ctx = await setup(t), { action, input, store, $ } = ctx;
  action('note'); input('.canvas-note-title', 'Keep these words');
  store.fail = true;
  assert.equal(await ctx.view.flush(), false);
  assert.match($('.canvas-save').textContent, /Save failed/);
  assert.equal(ctx.view.getBoard().nodes[0].title, 'Keep these words');
  assert.match(ctx.dom.window.sessionStorage.getItem('charta:canvas-recovery:/charta/:canvas_test'), /Keep these words/);
  assert.equal(await ctx.view.flush(), true);
  assert.equal(store.catalog.library.canvases[0].nodes[0].title, 'Keep these words');
  assert.equal(ctx.dom.window.sessionStorage.getItem('charta:canvas-recovery:/charta/:canvas_test'), null);
});
